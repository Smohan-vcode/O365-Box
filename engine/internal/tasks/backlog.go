// LoadAll reads every task and spike under root.
func LoadAll(root string) (map[string]*Task, error) {
	all := map[string]*Task{}
	for _, dir := range []string{"tasks", "spikes"} {
		files, err := filepath.Glob(filepath.Join(root, dir, "[TS]*-*.md"))
		if err != nil {
			return nil, err
		}
		for _, f := range files {
			t, err := Load(f)
			if err != nil {
				return nil, err
			}
			if _, dup := all[t.ID]; dup {
				return nil, fmt.Errorf("%s: id %s is used twice", f, t.ID)
			}
			all[t.ID] = t
		}
	}
	return all, nil
}

// Order sorts ids: spikes, then T0, T13, then T1 to T12 (the build order).
func Order(ids []string) {
	key := func(id string) (int, int, int) {
		if strings.HasPrefix(id, "S-") {
			n, _ := strconv.Atoi(id[2:])
			return -1, n, 0
		}
		a, b, _ := strings.Cut(strings.TrimPrefix(id, "T"), "-")
		track, _ := strconv.Atoi(a)
		n, _ := strconv.Atoi(b)
		rank := track + 1
		switch track {
		case 0:
			rank = 0
		case 13:
			rank = 1
		}
		return rank, 0, n
	}
	sort.Slice(ids, func(i, j int) bool {
		a1, a2, a3 := key(ids[i])
		b1, b2, b3 := key(ids[j])
		if a1 != b1 {
			return a1 < b1
		}
		if a2 != b2 {
			return a2 < b2
		}
		return a3 < b3
	})
}

// HasHumanSteps reports whether a task file lists human steps.
func HasHumanSteps(t *Task) bool {
	b, err := os.ReadFile(t.File)
	if err != nil {
		return false
	}
	_, after, ok := strings.Cut(string(b), "## Human steps")
	if !ok {
		return false
	}
	section, _, _ := strings.Cut(after, "\n## ")
	return strings.TrimSpace(section) != "- None."
}

// Index renders tasks/INDEX.md.
func Index(all map[string]*Task) string {
	ids := make([]string, 0, len(all))
	for id := range all {
		ids = append(ids, id)
	}
	Order(ids)
	var b strings.Builder
	b.WriteString("# Task index\n\nThe engine's development backlog, in dependency order within each track.\n" +
		"Spikes are in `spikes/`. Generated by `box backlog index` from front matter;\n" +
		"CI runs `box backlog check`.\n\n" +
		"| ID | Title | Priority | Size | Depends on | Human step | Status |\n" +
		"| --- | --- | --- | --- | --- | --- | --- |\n")
	for _, id := range ids {
		t := all[id]
		deps := strings.Join(t.DependsOn, ", ")
		if deps == "" {
			deps = "none"
		}
		human := ""
		if HasHumanSteps(t) {
			human = "yes"
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s |\n", t.ID, t.Title, t.Priority, t.Size, deps, human, t.Status)
	}
	return b.String()
}

var statusLine = regexp.MustCompile(`(?m)^status: \w+$`)

// MarkDone sets a task's status to DONE. It refuses while any dependency
// is not DONE.
func MarkDone(all map[string]*Task, id string) error {
	t := all[id]
	if t == nil {
		return fmt.Errorf("no task or spike %q", id)
	}
	var open []string
	for _, d := range t.DependsOn {
		if dt := all[d]; dt == nil || dt.Status != "DONE" {
			open = append(open, d)
		}
	}
	if len(open) > 0 {
		return fmt.Errorf("%s depends on %s, which is not DONE", id, strings.Join(open, ", "))
	}
	b, err := os.ReadFile(t.File)
	if err != nil {
		return err
	}
	if !statusLine.Match(b) {
		return fmt.Errorf("%s has no status line in its front matter", t.File)
	}
	b = statusLine.ReplaceAll(b, []byte("status: DONE"))
	if err := os.WriteFile(t.File, b, 0o644); err != nil {
		return err
	}
	t.Status = "DONE"
	return nil
}
