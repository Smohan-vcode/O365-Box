package cli

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/spf13/cobra"

	"github.com/Smohan-vcode/O365-Box/engine/internal/plan"
)

// renderRunbook builds runbooks/00-bootstrap.md from engine/gates.yaml, so
// the guide and the gate definitions cannot drift apart (SPEC §22).
func renderRunbook(root string) (string, error) {
	cat, err := plan.Load(filepath.Join(root, "engine", "providers"), filepath.Join(root, "engine", "gates.yaml"))
	if err != nil {
		return "", err
	}
	ids := make([]string, 0, len(cat.Gates))
	for id := range cat.Gates {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	var b strings.Builder
	b.WriteString("# Gates (manual steps the orchestrator checks)\n\n" +
		"Generated by `box runbook` from `engine/gates.yaml`; CI runs `box runbook --check`.\n" +
		"Do not edit by hand.\n\n" +
		"| ID | Step | Expected value | How it is checked |\n| --- | --- | --- | --- |\n")
	for _, id := range ids {
		g := cat.Gates[id]
		check := "confirmed with `box gate " + id + " --confirm`"
		if g.Check != "" {
			check = "step `" + g.Check + "` (`box gate " + id + " --check`)"
		} else if g.CheckTask != "" {
			check += "; automatic check planned in " + g.CheckTask
		}
		fmt.Fprintf(&b, "| %s | %s: %s | %s | %s |\n", g.ID, g.Title, g.Guide, g.Expected, check)
	}
	return b.String(), nil
}

func newRunbookCmd(g *globals) *cobra.Command {
	var check bool
	c := &cobra.Command{Use: "runbook", Short: "Render runbooks/00-bootstrap.md from the gate definitions", Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			root, err := g.root()
			if err != nil {
				return err
			}
			text, err := renderRunbook(root)
			if err != nil {
				return err
			}
			path := filepath.Join(root, "runbooks", "00-bootstrap.md")
			if check {
				cur, _ := os.ReadFile(path)
				if string(cur) != text {
					fmt.Fprintln(cmd.OutOrStdout(), "✗ runbook: runbooks/00-bootstrap.md is out of date; run box runbook")
					return exitError{ExitFailure}
				}
				fmt.Fprintln(cmd.OutOrStdout(), "✓ runbook: up to date with engine/gates.yaml")
				return nil
			}
			if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
				return err
			}
			fmt.Fprintln(cmd.OutOrStdout(), "✓ runbooks/00-bootstrap.md rendered")
			return nil
		}}
	c.Flags().BoolVar(&check, "check", false, "fail if the rendered runbook differs from the file")
	return c
}
